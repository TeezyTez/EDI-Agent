from pathlib import Path

from app.models.schema import RuleType, TransformRule


def generate_transform_code(rules: list[TransformRule], output_dir: str | Path) -> Path:
    """Generate a standalone Python transform module from TransformRule records."""
    target_dir = Path(output_dir)
    target_dir.mkdir(parents=True, exist_ok=True)
    output_path = target_dir / "transform.py"
    rules_payload = [rule.model_dump(mode="json") for rule in rules]
    output_path.write_text(
        f'''"""Generated by EDI Mapping Agent. Review before production use."""
from datetime import datetime


RULES = {rules_payload!r}


def _format_date(value, input_format, output_format):
    if value in (None, ""):
        return value
    if isinstance(value, datetime):
        return value.strftime(output_format)
    try:
        return datetime.strptime(str(value), input_format).strftime(output_format)
    except ValueError:
        return value


def _apply_rule(source, rule):
    rule_type = rule["rule_type"]
    source_field = rule.get("source_field")
    if rule_type == "{RuleType.DEFAULT_VALUE.value}":
        return rule.get("default_value")
    value = source.get(source_field) if source_field else None
    if rule_type == "{RuleType.DATE_FORMAT.value}":
        return _format_date(value, rule.get("date_input_format") or "%Y-%m-%d", rule.get("date_output_format") or "%Y-%m-%d")
    if rule_type == "{RuleType.ENUM_MAPPING.value}":
        return rule.get("enum_map", {{}}).get(str(value), value)
    return value


def transform_record(source):
    """Transform one source record into one target record."""
    return {{rule["target_field"]: _apply_rule(source, rule) for rule in RULES}}


def transform_records(records):
    """Transform a list of source records."""
    return [transform_record(record) for record in records]
''',
        encoding="utf-8",
    )
    return output_path
